//! MKLight Metal compute backend (macOS).
//!
//! * [`MetalContext`]: device selection, command queue, the shader library
//!   (embedded offline-compiled `.metallib`, or runtime compilation from the
//!   embedded source with fast-math off), and a pipeline-state cache keyed by
//!   function name + function-constant values.
//! * [`SharedBuffer`]: typed shared-storage buffers (unified memory on Apple
//!   Silicon) with safe slice access while no GPU work references them.
//! * Command buffers are committed and awaited on a worker thread; completion
//!   status, errors and GPU timestamps are reported per command buffer.
//! * [`MetalBackend`] implements `mklight_gpu::ComputeBackend`, including the
//!   sequential / path trace kernel (`shaders/trace.metal`, bit-identical to
//!   `mklight_gpu::trace_kernel`). At start-up it runs a numerics probe and
//!   refuses double-float work (reductions, traces) if the device or
//!   compiler would break error-free transforms.
//!
//! On other platforms this crate compiles to an empty shell whose
//! [`is_available`] returns `false`.

#[cfg(target_os = "macos")]
mod backend;
#[cfg(target_os = "macos")]
mod buffer;
#[cfg(target_os = "macos")]
mod context;

#[cfg(target_os = "macos")]
pub use backend::{MetalBackend, probe_inputs};
#[cfg(target_os = "macos")]
pub use buffer::SharedBuffer;
#[cfg(target_os = "macos")]
pub use context::{
    CommandStats, DeviceSelector, FunctionConstant, LibraryChoice, LibraryOrigin, MetalContext,
    MetalOptions, PipelineKey,
};

/// Embedded shaders (generated by build.rs).
#[cfg(target_os = "macos")]
pub mod shaders {
    include!(concat!(env!("OUT_DIR"), "/shaders.rs"));
}

/// Whether a Metal device can be used on this machine.
pub fn is_available() -> bool {
    #[cfg(target_os = "macos")]
    {
        objc2_metal::MTLCreateSystemDefaultDevice().is_some()
    }
    #[cfg(not(target_os = "macos"))]
    {
        false
    }
}

