//! Generates `header_consts.rs` from the integer `#define MKL_*` lines of
//! `include/mklight_gpu_types.h`, so the C header is the only place a layout
//! constant is written down. Supported forms: `123u`, `0xABCDu`, `(1u << 5)`.

use std::fmt::Write as _;
use std::{env, fs, path::PathBuf};

fn parse_value(v: &str) -> Option<u64> {
    let v = v.trim();
    let num = |s: &str| -> Option<u64> {
        let s = s.trim().trim_end_matches(['u', 'U']);
        if let Some(h) = s.strip_prefix("0x").or_else(|| s.strip_prefix("0X")) {
            u64::from_str_radix(h, 16).ok()
        } else {
            s.parse().ok()
        }
    };
    if let Some(inner) = v.strip_prefix('(').and_then(|x| x.strip_suffix(')')) {
        let (a, b) = inner.split_once("<<")?;
        return Some(num(a)? << num(b)?);
    }
    num(v)
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let header = manifest.join("include/mklight_gpu_types.h");
    println!("cargo:rerun-if-changed={}", header.display());
    let text = fs::read_to_string(&header).expect("read mklight_gpu_types.h");

    let mut out = String::from("// @generated by build.rs from include/mklight_gpu_types.h\n");
    for line in text.lines() {
        let Some(rest) = line.trim().strip_prefix("#define ") else {
            continue;
        };
        let mut it = rest.splitn(2, char::is_whitespace);
        let (Some(name), Some(value)) = (it.next(), it.next()) else {
            continue;
        };
        if !name.starts_with("MKL_") || name.contains('(') {
            continue;
        }
        // Strip a trailing C comment.
        let value = value.split("/*").next().unwrap_or("").trim();
        if let Some(v) = parse_value(value) {
            let ty = if v <= u32::MAX as u64 { "u32" } else { "u64" };
            writeln!(out, "pub const {name}: {ty} = {v:#x};").unwrap();
        }
    }
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("header_consts.rs");
    fs::write(dest, out).unwrap();
}
